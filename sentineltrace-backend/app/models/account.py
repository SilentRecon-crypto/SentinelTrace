"""
Account ORM model.

Fields map 1:1 onto data/model_a/accounts.csv (account_id, acc_type,
created_day) as generated by research_model_a/generate_graph_v1.py. No
fields were invented; account_id is used directly as the primary key since
the source data already guarantees uniqueness.
"""
from sqlalchemy import Integer, String
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.database import Base


class Account(Base):
    __tablename__ = "accounts"

    # Source field, used directly as primary key (unique in source data).
    account_id: Mapped[int] = mapped_column(Integer, primary_key=True)

    # Source fields (verbatim from accounts.csv)
    acc_type: Mapped[str] = mapped_column(String(32), nullable=False, index=True)
    created_day: Mapped[int] = mapped_column(Integer, nullable=False)

    outgoing_transactions: Mapped[list["Transaction"]] = relationship(
        "Transaction", foreign_keys="Transaction.src_account_id", back_populates="src_account"
    )
    incoming_transactions: Mapped[list["Transaction"]] = relationship(
        "Transaction", foreign_keys="Transaction.dst_account_id", back_populates="dst_account"
    )
