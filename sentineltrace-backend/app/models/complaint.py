"""
Complaint ORM model.

Fields map 1:1 onto data/model_a/complaints.csv as generated by
research_model_a/generate_graph_v1.py: complaint_id, victim, day,
fraud_amount, n_hops, chain, used_shared_pool, mode, missing_hop_idx.

`chain` (the ground-truth mule-chain account-ID sequence) is stored as a
native PostgreSQL integer array rather than the comma-joined string used in
the CSV, since Postgres supports this directly and it avoids ad-hoc string
parsing at query time. This is a type-mapping choice for storage, not an
invented field — the values are identical to the source `chain` column.
"""
from sqlalchemy import Boolean, Float, Integer, String
from sqlalchemy.dialects.postgresql import ARRAY
from sqlalchemy.orm import Mapped, mapped_column

from app.database import Base


class Complaint(Base):
    __tablename__ = "complaints"

    # Source field, used directly as primary key (unique in source data).
    complaint_id: Mapped[int] = mapped_column(Integer, primary_key=True)

    # Source fields (verbatim from complaints.csv)
    victim: Mapped[int] = mapped_column(Integer, nullable=False)
    day: Mapped[int] = mapped_column(Integer, nullable=False, index=True)
    fraud_amount: Mapped[float] = mapped_column(Float, nullable=False)
    n_hops: Mapped[int] = mapped_column(Integer, nullable=False)
    chain: Mapped[list[int]] = mapped_column(ARRAY(Integer), nullable=False)
    used_shared_pool: Mapped[bool] = mapped_column(Boolean, nullable=False)
    mode: Mapped[str] = mapped_column(String(32), nullable=False)
    missing_hop_idx: Mapped[int] = mapped_column(Integer, nullable=False)
